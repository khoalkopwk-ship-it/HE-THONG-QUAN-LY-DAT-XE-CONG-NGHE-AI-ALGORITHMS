class CampusGraph:
    """Đồ thị đường đi mô phỏng khu Làng Đại học / ĐHQG TP.HCM, nhập từ GRAPH.docx.

    Lưu ý cho báo cáo:
    - OpenStreetMap chỉ làm nền trực quan.
    - BFS / Local Search / UCS chạy trên graph node-edge này.
    - Tài xế, khách hàng và điểm đến được sinh ngẫu nhiên trên cạnh đường.
    - Hẻm cụt được biểu diễn bằng node chỉ có 1 đường nối vào.
    """

    def __init__(self) -> None:
        self.nodes: dict[str, Node] = {}
        self.adj: dict[str, list[tuple[str, float]]] = {}
        self.base_edges: list[Edge] = []
        self._base_edge_weights: dict[tuple[str, str], float] = {}

        # Road condition lưu tình trạng từng cạnh gốc:
        # bad -> nhân 1.5, very_bad -> nhân 2, blocked -> không cho đi qua.
        self.road_conditions: dict[tuple[str, str], str] = {}
        for edge_key, condition in GRAPH_ROAD_CONDITIONS.items():
            normalized_key = self._edge_key(edge_key[0], edge_key[1])
            if condition != ROAD_NORMAL:
                self.road_conditions[normalized_key] = condition

        # Node động là tài xế/khách/điểm đến được gắn tạm vào graph khi chạy demo.
        self._dynamic_node_ids: set[str] = set()
        self._dynamic_counter = 0
        # Mỗi node động nhớ cạnh gốc mà nó bám vào để khi đánh dấu đường xấu/cấm,
        # trọng số nối vào graph cũng được cập nhật đồng bộ.
        self._dynamic_edge_links: dict[str, list[tuple[str, float, tuple[str, str]]]] = {}

        self._build_from_node_edge_graph()
        self.base_node_ids: set[str] = set(self.nodes.keys())
        self.dead_end_ids: set[str] = set(GRAPH_DEAD_ENDS)

    # ------------------------------------------------------------------
    # Build base road network
    # ------------------------------------------------------------------


    def _build_from_node_edge_graph(self) -> None:
        """Tạo graph từ danh sách node và edge rõ ràng."""

        for node_id, (lat, lng) in GRAPH_NODES.items():
            self.nodes[node_id] = Node(node_id, node_id, lat, lng)
            self.adj[node_id] = []

        for a, b in GRAPH_EDGES_RAW:
            self._add_edge(a, b)

    def _edge_key(self, a: str, b: str) -> tuple[str, str]:
        """Chuẩn hóa key cạnh để (A, B) và (B, A) được xem là một đường."""

        return tuple(sorted((a, b)))

    def _condition_factor(self, edge_key: tuple[str, str]) -> float | None:
        """Trả về hệ số trọng số của cạnh; None nghĩa là đường bị cấm."""

        condition = self.road_conditions.get(edge_key, ROAD_NORMAL)
        if condition == ROAD_BLOCKED:
            return None
        return ROAD_WEIGHT_FACTORS.get(condition, 1.0)

    def _append_weighted_edge(self, a: str, b: str, base_weight: float, edge_key: tuple[str, str]) -> None:
        """Thêm cạnh vào adjacency list sau khi xét tình trạng đường."""

        factor = self._condition_factor(edge_key)
        if factor is None:
            return

        weight = base_weight * factor
        self.adj[a].append((b, weight))
        self.adj[b].append((a, weight))

    def _add_edge(self, a: str, b: str, factor: float = 1.06) -> None:
        """Thêm cạnh 2 chiều giữa 2 node.

        factor = 1.06 dùng để mô phỏng đường đi thực tế hơi dài hơn
        khoảng cách chim bay giữa 2 tọa độ. Khi cạnh được đánh dấu đường xấu,
        trọng số dùng cho UCS/A* sẽ tiếp tục nhân thêm 1.5 hoặc 2.0.
        """

        if a == b:
            return

        if a not in self.nodes:
            raise KeyError(f"Node không tồn tại: {a}")

        if b not in self.nodes:
            raise KeyError(f"Node không tồn tại: {b}")

        edge_key = self._edge_key(a, b)
        if edge_key in self._base_edge_weights:
            return

        na = self.nodes[a]
        nb = self.nodes[b]

        base_weight = haversine_km(na.lat, na.lng, nb.lat, nb.lng) * factor
        self._base_edge_weights[edge_key] = base_weight
        self.base_edges.append(Edge(a=a, b=b, weight_km=base_weight))
        self._append_weighted_edge(a, b, base_weight, edge_key)

    def add_base_node(self, node_id: str, lat: float, lng: float) -> None:
        """Thêm/cập nhật node nền để mọi chức năng dùng ngay trong phiên chạy."""

        self.nodes[node_id] = Node(node_id, node_id, lat, lng)
        self.adj.setdefault(node_id, [])
        self.base_node_ids.add(node_id)

    def add_base_edge(self, a: str, b: str, condition: str = ROAD_NORMAL) -> None:
        """Thêm cạnh nền mới và áp dụng tình trạng đường nếu có."""

        self._add_edge(a, b)
        self.set_edge_condition(a, b, condition)


    def remove_base_node(self, node_id: str) -> None:
        """Xóa node nền và toàn bộ cạnh liên kết với node đó."""

        if node_id not in self.base_node_ids:
            return

        linked_keys = [self._edge_key(edge.a, edge.b) for edge in self.base_edges if node_id in (edge.a, edge.b)]
        self.base_edges = [edge for edge in self.base_edges if node_id not in (edge.a, edge.b)]
        for key in linked_keys:
            self._base_edge_weights.pop(key, None)
            self.road_conditions.pop(key, None)

        self.nodes.pop(node_id, None)
        self.adj.pop(node_id, None)
        self.base_node_ids.discard(node_id)
        self.dead_end_ids.discard(node_id)

        for dynamic_id, links in list(self._dynamic_edge_links.items()):
            self._dynamic_edge_links[dynamic_id] = [
                link for link in links if link[0] != node_id and link[2] not in linked_keys
            ]

        self._rebuild_adjacency()

    def replace_base_graph(
        self,
        nodes: dict[str, tuple[float, float]],
        edges: list[tuple[str, str]],
        dead_ends: set[str] | None = None,
        road_conditions: dict[tuple[str, str], str] | None = None,
    ) -> None:
        """Thay toàn bộ graph nền trong phiên chạy."""

        self.nodes.clear()
        self.adj.clear()
        self.base_edges.clear()
        self._base_edge_weights.clear()
        self.road_conditions.clear()
        self._dynamic_node_ids.clear()
        self._dynamic_edge_links.clear()

        for node_id, (lat, lng) in nodes.items():
            self.nodes[node_id] = Node(node_id, node_id, lat, lng)
            self.adj[node_id] = []

        self.base_node_ids = set(nodes.keys())
        self.dead_end_ids = set(dead_ends or set())

        for a, b in edges:
            if a in self.nodes and b in self.nodes:
                self._add_edge(a, b)

        for (a, b), condition in (road_conditions or {}).items():
            self.set_edge_condition(a, b, condition)

    def _rebuild_adjacency(self) -> None:
        """Dựng lại adjacency list sau khi trạng thái đường thay đổi."""

        for node_id in self.nodes:
            self.adj[node_id] = []

        for edge in self.base_edges:
            edge_key = self._edge_key(edge.a, edge.b)
            base_weight = self._base_edge_weights.get(edge_key, edge.weight_km)
            self._append_weighted_edge(edge.a, edge.b, base_weight, edge_key)

        for dynamic_id, links in self._dynamic_edge_links.items():
            if dynamic_id not in self.nodes:
                continue
            for endpoint_id, base_weight, parent_key in links:
                if endpoint_id not in self.nodes:
                    continue
                self._append_weighted_edge(dynamic_id, endpoint_id, base_weight, parent_key)

    def set_edge_condition(self, a: str, b: str, condition: str) -> None:
        """Cập nhật trạng thái một cạnh và áp dụng ngay cho thuật toán tìm đường."""

        edge_key = self._edge_key(a, b)
        if edge_key not in self._base_edge_weights:
            return

        if condition == ROAD_NORMAL:
            self.road_conditions.pop(edge_key, None)
        elif condition in ROAD_CONDITION_LABELS:
            self.road_conditions[edge_key] = condition
        else:
            raise ValueError(f"Tình trạng đường không hợp lệ: {condition}")

        self._rebuild_adjacency()

    def get_edge_condition(self, a: str, b: str) -> str:
        """Lấy trạng thái hiện tại của một cạnh."""

        return self.road_conditions.get(self._edge_key(a, b), ROAD_NORMAL)

    def road_condition_items(self) -> list[tuple[str, str, str]]:
        """Danh sách cạnh đang bị đánh dấu, dùng để UI hiển thị và export."""

        return [(a, b, condition) for (a, b), condition in sorted(self.road_conditions.items())]


    # ------------------------------------------------------------------
    # Dynamic nodes for random drivers/customers/destinations on road edges
    # ------------------------------------------------------------------
    def reset_dynamic_nodes(self) -> None:
        """Xóa các node động đã sinh cho tài xế, khách hàng, điểm đến."""

        if not self._dynamic_node_ids:
            return

        for node_id in list(self._dynamic_node_ids):
            self.nodes.pop(node_id, None)
            self.adj.pop(node_id, None)

        for node_id in list(self.adj.keys()):
            self.adj[node_id] = [
                (neighbor_id, weight)
                for neighbor_id, weight in self.adj[node_id]
                if neighbor_id not in self._dynamic_node_ids
            ]

        self._dynamic_node_ids.clear()
        self._dynamic_edge_links.clear()

    def add_point_on_edge(
        self,
        edge: Edge,
        ratio: float,
        prefix: str,
    ) -> tuple[str, float, float]:
        """Sinh một node động nằm trên một cạnh đường.

        ratio:
        - 0.0 gần đầu cạnh a
        - 1.0 gần đầu cạnh b

        Node động sẽ nối với cả 2 đầu cạnh để UCS/BFS có thể chạy.
        """

        ratio = max(0.02, min(0.98, ratio))

        a = self.nodes[edge.a]
        b = self.nodes[edge.b]

        lat = a.lat + (b.lat - a.lat) * ratio
        lng = a.lng + (b.lng - a.lng) * ratio

        self._dynamic_counter += 1
        node_id = f"{prefix}_{self._dynamic_counter:04d}"

        self.nodes[node_id] = Node(node_id, node_id, lat, lng)
        self.adj[node_id] = []
        self._dynamic_node_ids.add(node_id)

        parent_key = self._edge_key(edge.a, edge.b)
        weight_a = edge.weight_km * ratio
        weight_b = edge.weight_km * (1.0 - ratio)
        self._dynamic_edge_links[node_id] = [
            (edge.a, weight_a, parent_key),
            (edge.b, weight_b, parent_key),
        ]
        self._append_weighted_edge(node_id, edge.a, weight_a, parent_key)
        self._append_weighted_edge(node_id, edge.b, weight_b, parent_key)

        return node_id, lat, lng


    def _point_to_edge_distance_km(self, lat: float, lng: float, edge: Edge) -> tuple[float, float]:
        """Trả về (khoảng cách tới đoạn edge, tỷ lệ chiếu trên edge).

        Hàm dùng hệ tọa độ phẳng cục bộ để kiểm tra người dùng click có gần
        tuyến đường trong graph hay không. Nếu gần, UI có thể tạo node động
        tại điểm click và nối vào cạnh đường gần nhất.
        """

        a = self.nodes[edge.a]
        b = self.nodes[edge.b]
        radius_km = 6371.0
        ref_lat = math.radians((lat + a.lat + b.lat) / 3.0)
        ref_lng = math.radians((lng + a.lng + b.lng) / 3.0)

        def to_xy(point_lat: float, point_lng: float) -> tuple[float, float]:
            x = (math.radians(point_lng) - ref_lng) * math.cos(ref_lat) * radius_km
            y = math.radians(point_lat) * radius_km
            return x, y

        px, py = to_xy(lat, lng)
        ax, ay = to_xy(a.lat, a.lng)
        bx, by = to_xy(b.lat, b.lng)
        dx = bx - ax
        dy = by - ay
        denom = dx * dx + dy * dy

        if denom <= 1e-12:
            return haversine_km(lat, lng, a.lat, a.lng), 0.0

        ratio = ((px - ax) * dx + (py - ay) * dy) / denom
        ratio = max(0.0, min(1.0, ratio))
        closest_x = ax + ratio * dx
        closest_y = ay + ratio * dy
        distance = math.sqrt((px - closest_x) ** 2 + (py - closest_y) ** 2)
        return distance, ratio

    def add_connected_point_near_road(
        self,
        lat: float,
        lng: float,
        prefix: str,
        max_distance_km: float = 0.08,
    ) -> tuple[str, float, float, float] | None:
        """Tạo node động tại tọa độ người dùng chọn nếu điểm đó gần đường.

        Nếu tọa độ cách cạnh đường gần nhất quá `max_distance_km`, trả về None
        để UI hiện cảnh báo "không xác định". Nếu hợp lệ, node mới được giữ tại
        đúng vị trí click và nối vào 2 đầu cạnh gần nhất, nhờ đó A* có thể tìm
        đường từ tài xế/điểm đón/điểm đến vào graph nội bộ.
        """

        if not self.base_edges:
            return None

        available_edges = [
            edge for edge in self.base_edges
            if self.get_edge_condition(edge.a, edge.b) != ROAD_BLOCKED
        ]
        if not available_edges:
            return None

        nearest_edge = min(
            available_edges,
            key=lambda edge: self._point_to_edge_distance_km(lat, lng, edge)[0],
        )
        distance_km, _ratio = self._point_to_edge_distance_km(lat, lng, nearest_edge)
        if distance_km > max_distance_km:
            return None

        self._dynamic_counter += 1
        node_id = f"{prefix}_{self._dynamic_counter:04d}"
        self.nodes[node_id] = Node(node_id, node_id, lat, lng)
        self.adj[node_id] = []
        self._dynamic_node_ids.add(node_id)

        parent_key = self._edge_key(nearest_edge.a, nearest_edge.b)
        links: list[tuple[str, float, tuple[str, str]]] = []
        for endpoint_id in (nearest_edge.a, nearest_edge.b):
            endpoint = self.nodes[endpoint_id]
            base_weight = haversine_km(lat, lng, endpoint.lat, endpoint.lng) * 1.06
            links.append((endpoint_id, base_weight, parent_key))
            self._append_weighted_edge(node_id, endpoint_id, base_weight, parent_key)
        self._dynamic_edge_links[node_id] = links

        return node_id, lat, lng, distance_km

    def random_point_on_road(self, prefix: str = "P") -> tuple[str, float, float]:
        """Sinh một điểm ngẫu nhiên nằm trên bất kỳ cạnh đường nào của graph."""

        available_edges = [
            edge for edge in self.base_edges
            if self.get_edge_condition(edge.a, edge.b) != ROAD_BLOCKED
        ]
        if not available_edges:
            raise RuntimeError("Graph chưa có cạnh đường nào có thể đi qua.")

        total = sum(edge.weight_km for edge in available_edges)
        pick = random.uniform(0.0, total)

        acc = 0.0
        selected = available_edges[-1]

        for edge in available_edges:
            acc += edge.weight_km
            if acc >= pick:
                selected = edge
                break

        ratio = random.uniform(0.08, 0.92)
        return self.add_point_on_edge(selected, ratio, prefix)

    # ------------------------------------------------------------------
    # Helpers used by algorithms and UI
    # ------------------------------------------------------------------
    def nearest_node_id(self, lat: float, lng: float) -> str:
        """Tìm node gần nhất với một tọa độ bất kỳ."""

        return min(
            self.nodes,
            key=lambda node_id: haversine_km(
                lat,
                lng,
                self.nodes[node_id].lat,
                self.nodes[node_id].lng,
            ),
        )

    def node_position(self, node_id: str) -> tuple[float, float]:
        node = self.nodes[node_id]
        return node.lat, node.lng

    def edges_raw(self) -> list[tuple[str, str]]:
        """Trả về danh sách cạnh nền hiện tại theo ID node."""

        return [(edge.a, edge.b) for edge in self.base_edges]


    def base_node_positions(self) -> list[tuple[str, float, float]]:
        """Trả về danh sách node gốc để UI vẽ marker node giao lộ."""

        return [
            (node_id, self.nodes[node_id].lat, self.nodes[node_id].lng)
            for node_id in sorted(self.base_node_ids)
        ]
